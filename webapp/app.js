// ------------------------------------------------------------------ BLE link to the pager (MeshCore companion protocol)

class PagerLink {
  constructor() { this.queue = []; this.waiters = []; this.device = null; }

  async connect() {
    this.device = await navigator.bluetooth.requestDevice({
      filters: [{ namePrefix: "MeshCore-" }, { services: [NUS] }],
      optionalServices: [NUS],
    });
    this.device.addEventListener("gattserverdisconnected", () => this.onDisconnect && this.onDisconnect());
    const server = await this.device.gatt.connect();
    const svc = await server.getPrimaryService(NUS);
    this.rx = await svc.getCharacteristic(NUS_RX);
    this.tx = await svc.getCharacteristic(NUS_TX);
    this.tx.addEventListener("characteristicvaluechanged", (e) => {
      const v = e.target.value;
      this.push(new Uint8Array(v.buffer, v.byteOffset, v.byteLength).slice());
    });
    await this.tx.startNotifications();   // the OS asks for the PIN here (first time)
    return this.device.name;
  }

  get connected() { return this.device && this.device.gatt.connected; }
  disconnect() { if (this.connected) this.device.gatt.disconnect(); }

  push(frame) {
    if (!(frame[0] === RESP_OK || frame[0] === RESP_ERR || frame[0] === CMD_CONFIG || frame[0] === CMD_OTA)) return;   // 0x80+: pushes
    const w = this.waiters.shift();
    if (w) w(frame); else this.queue.push(frame);
  }

  reply(timeout = 15000) {
    if (this.queue.length) return Promise.resolve(this.queue.shift());
    return new Promise((resolve, reject) => {
      const t = setTimeout(() => { this.waiters = this.waiters.filter((x) => x !== done); reject(new Error("no answer from the pager")); }, timeout);
      const done = (f) => { clearTimeout(t); resolve(f); };
      this.waiters.push(done);
    });
  }

  async send(bytes) { await this.rx.writeValueWithResponse(bytes); }

  async request(bytes, timeout) { await this.send(bytes); return this.reply(timeout); }

  // 0x70 / 0x71 result frames: code, status, line u16, UTF-8 message
  static result(f) {
    if (f[0] === RESP_ERR) throw new Error(ERR_NAMES[f[1]] || `error ${f[1]}`);
    if (f[0] === RESP_OK) return { status: 0, line: 0, msg: "" };
    return { status: f[1], line: f[2] | (f[3] << 8), msg: dec.decode(f.subarray(4)) };
  }

  async info() {
    const r = PagerLink.result(await this.request(new Uint8Array([CMD_OTA, OTA_INFO])));
    return Object.fromEntries(r.msg.split(" ").filter((kv) => kv.includes("=")).map((kv) => kv.split("=")));
  }

  async configCmd(op) { return PagerLink.result(await this.request(new Uint8Array([CMD_CONFIG, op]))); }

  async uploadYaml(yaml) {
    const data = enc.encode(yaml);
    if (data.length > 4096) throw new Error("setup larger than 4096 bytes");
    const expectOk = async (frame) => {
      const f = await this.request(frame);
      if (f[0] === RESP_OK) return;
      throw new Error(PagerLink.result(f).msg || "unexpected answer");   // result() throws for ERR frames
    };
    await expectOk(new Uint8Array([CMD_CONFIG, CFG_BEGIN, data.length & 0xff, data.length >> 8]));
    for (let off = 0; off < data.length; off += CFG_CHUNK) {
      const chunk = data.subarray(off, off + CFG_CHUNK);
      const f = new Uint8Array(4 + chunk.length);
      f.set([CMD_CONFIG, CFG_DATA, off & 0xff, off >> 8]);
      f.set(chunk, 4);
      await expectOk(f);
    }
    return this.configCmd(CFG_COMMIT);
  }

  // ESP32: stream the app image, acknowledgement every OTA_WINDOW frames
  async updateEsp32(image, progress) {
    const begin = new Uint8Array(2 + 4 + 16);
    begin.set([CMD_OTA, OTA_BEGIN]);
    new DataView(begin.buffer).setUint32(2, image.length, true);
    begin.set(md5(image), 6);
    let r = PagerLink.result(await this.request(begin));
    if (r.status) throw new Error(r.msg);
    const n = Math.ceil(image.length / OTA_CHUNK);
    const t0 = performance.now();
    for (let k = 0; k < n; k++) {
      const off = k * OTA_CHUNK, chunk = image.subarray(off, off + OTA_CHUNK);
      const ack = k % OTA_WINDOW === OTA_WINDOW - 1 || k === n - 1;
      const f = new Uint8Array(7 + chunk.length);
      f.set([CMD_OTA, OTA_DATA]);
      new DataView(f.buffer).setUint32(2, off, true);
      f[6] = ack ? 1 : 0;
      f.set(chunk, 7);
      await this.send(f);
      if (ack) {
        const a = await this.reply();
        if (a[0] !== RESP_OK) throw new Error(PagerLink.result(a).msg || "update failed");
        progress(off + chunk.length, image.length, (off + chunk.length) / ((performance.now() - t0) / 1000));
      }
    }
    r = PagerLink.result(await this.request(new Uint8Array([CMD_OTA, OTA_END]), 30000));
    if (r.status) throw new Error(r.msg);
    return r.msg;
  }

  async enterDfu() {
    const r = PagerLink.result(await this.request(new Uint8Array([CMD_OTA, OTA_DFU])));
    if (r.status) throw new Error(r.msg);
  }
}

// ------------------------------------------------------------------ Nordic legacy DFU (T114 bootloader)

async function legacyDfu(image, init, progress, log) {
  const device = await navigator.bluetooth.requestDevice({
    filters: [{ services: [DFU] }, { namePrefix: "AdaDFU" }, { namePrefix: "T114" }],
    optionalServices: [DFU],
  });
  log(`Bootloader: ${device.name || "?"}`);
  const server = await device.gatt.connect();
  const svc = await server.getPrimaryService(DFU);
  const ctrl = await svc.getCharacteristic(DFU_CONTROL);
  const pkt = await svc.getCharacteristic(DFU_PACKET);
  const notes = [], waiters = [];
  ctrl.addEventListener("characteristicvaluechanged", (e) => {
    const v = e.target.value, f = new Uint8Array(v.buffer, v.byteOffset, v.byteLength).slice();
    const w = waiters.shift();
    if (w) w(f); else notes.push(f);
  });
  await ctrl.startNotifications();
  const note = (timeout = 60000) => notes.length ? Promise.resolve(notes.shift()) : new Promise((res, rej) => {
    const t = setTimeout(() => rej(new Error("DFU: no answer")), timeout);
    waiters.push((f) => { clearTimeout(t); res(f); });
  });
  const expect = async (op) => {
    for (;;) {
      const f = await note();
      if (f[0] === 0x10 && f[1] === op) { if (f[2] !== 1) throw new Error(`DFU step ${op} failed (status ${f[2]})`); return; }
    }
  };
  const control = (bytes) => ctrl.writeValueWithResponse(new Uint8Array(bytes));
  const packet = (bytes) => pkt.writeValueWithoutResponse(bytes);

  try {
    await control([0x01, 0x04]);                                   // START_DFU, application
    const sizes = new Uint8Array(12);
    new DataView(sizes.buffer).setUint32(8, image.length, true);   // softdevice 0, bootloader 0, app
    await packet(sizes);
    await expect(0x01);
    await control([0x02, 0x00]);                                   // init packet
    await packet(init);
    await control([0x02, 0x01]);
    await expect(0x02);
    await control([0x08, DFU_PRN, 0]);                             // receipt every DFU_PRN packets
    await control([0x03]);                                         // RECEIVE_FIRMWARE_IMAGE
    const t0 = performance.now();
    const n = Math.ceil(image.length / DFU_PKT);
    for (let k = 0; k < n; k++) {
      await packet(image.subarray(k * DFU_PKT, (k + 1) * DFU_PKT));
      if (k % DFU_PRN === DFU_PRN - 1) {
        let f;
        do { f = await note(30000); if (f[0] === 0x10) throw new Error("DFU aborted by the bootloader"); } while (f[0] !== 0x11);
        const done = new DataView(f.buffer).getUint32(1, true);
        progress(done, image.length, done / ((performance.now() - t0) / 1000));
      }
    }
    await expect(0x03);
    progress(image.length, image.length, 0);
    await control([0x04]);                                         // VALIDATE
    await expect(0x04);
    try { await control([0x05]); } catch (e) { /* resets right away */ }   // ACTIVATE_AND_RESET
  } finally {
    if (device.gatt.connected) device.gatt.disconnect();
  }
}

