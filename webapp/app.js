// ------------------------------------------------------------------ password + key

// 4 random words, uniform (rejection sampling on 16-bit values: 7776 * 8 = 62208 < 65536)
export function generatePassphrase(n = 4) {
  const out = [];
  const buf = new Uint16Array(1);
  while (out.length < n) {
    crypto.getRandomValues(buf);
    if (buf[0] < WORDS.length * 8) out.push(WORDS[buf[0] % WORDS.length]);
  }
  return out.join("-");
}

// case, spaces and separators don't matter: "Tulip Harbor-orbit_PASTE" == "tulip-harbor-orbit-paste"
export function normalizePassphrase(p) {
  return p.normalize("NFC").toLowerCase().split(/[\s\-_.,;:+\/]+/).filter(Boolean).join("-");
}

export function passphraseStrength(p) {
  const words = normalizePassphrase(p).split("-").filter(Boolean);
  const listed = words.length > 0 && words.every((w) => WORDS.includes(w));
  if (listed) return { bits: Math.round(words.length * Math.log2(WORDS.length)), words: words.length, listed };
  const chars = normalizePassphrase(p).length;
  return { bits: Math.round(chars * 2.5), words: words.length, listed };   // rough guess for own passwords
}

export async function deriveChannelKey(passphrase, channelName) {
  const pw = enc.encode(normalizePassphrase(passphrase));
  const salt = enc.encode(KDF_SALT_PREFIX + channelName);
  const base = await crypto.subtle.importKey("raw", pw, "PBKDF2", false, ["deriveBits"]);
  const bits = await crypto.subtle.deriveBits({ name: "PBKDF2", hash: "SHA-256", salt, iterations: KDF_ITERATIONS }, base, 128);
  return [...new Uint8Array(bits)].map((b) => b.toString(16).padStart(2, "0")).join("");
}

// ------------------------------------------------------------------ YAML (subset the pager parses)

const q = (s) => '"' + s.replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';

export function buildYaml(setup) {
  const lines = ["# MSPager setup, generated by the web app", "version: 1"];
  if (setup.nickname) lines.push(`nickname: ${q(setup.nickname)}`);
  if (setup.region) lines.push("radio:", `  region: ${setup.region}`);
  if (setup.channel) lines.push("channel:", `  name: ${q(setup.channel)}`, `  key: ${setup.key}`);
  if (setup.questions.length) {
    lines.push("questions:");
    for (const qu of setup.questions) {
      lines.push(`  - text: ${q(qu.text)}`, `    replies: [${qu.replies.map(q).join(", ")}]`);
    }
  }
  return lines.join("\n") + "\n";
}

// same limits as the pager (PagerConfig.h); the pager checks again and reports the line
export function validateSetup(s) {
  const errors = [];
  if (s.nickname && (bytesOf(s.nickname) > 31 || /[:\[\]]/.test(s.nickname))) errors.push("Nickname: max 31 bytes, no : [ ]");
  if (!s.channel) errors.push("Channel name is missing");
  else if (bytesOf(s.channel) > 31 || s.channel.toLowerCase() === "public") errors.push("Channel name: max 31 bytes, not 'Public'");
  if (!/^[0-9a-f]{32}$/.test(s.key || "")) errors.push("Channel key missing: enter a password or a 32-character hex key");
  if (s.questions.length > 12) errors.push("At most 12 questions");
  const seen = new Set();
  s.questions.forEach((qu, i) => {
    const n = `Question ${i + 1}`;
    if (!qu.text) errors.push(`${n}: text is empty`);
    if (bytesOf(qu.text) > 40) errors.push(`${n}: longer than 40 bytes`);
    if (seen.has(qu.text)) errors.push(`${n}: duplicate text`);
    seen.add(qu.text);
    if (qu.replies.length < 1 || qu.replies.length > 6) errors.push(`${n}: 1 to 6 replies`);
    qu.replies.forEach((r) => { if (bytesOf(r) > 40) errors.push(`${n}: reply "${r}" longer than 40 bytes`); });
  });
  return errors;
}

// ------------------------------------------------------------------ MD5 (WebCrypto has none; the ESP32 update checks it)

export function md5(data) {
  const K = new Uint32Array(64), S = [7, 12, 17, 22, 5, 9, 14, 20, 4, 11, 16, 23, 6, 10, 15, 21];
  for (let i = 0; i < 64; i++) K[i] = Math.floor(Math.abs(Math.sin(i + 1)) * 2 ** 32) >>> 0;
  const len = data.length, total = ((len + 8) >> 6) + 1;
  const buf = new Uint8Array(total * 64);
  buf.set(data);
  buf[len] = 0x80;
  const dv = new DataView(buf.buffer);
  dv.setUint32(total * 64 - 8, (len * 8) >>> 0, true);
  dv.setUint32(total * 64 - 4, Math.floor(len / 2 ** 29), true);
  let a0 = 0x67452301, b0 = 0xefcdab89, c0 = 0x98badcfe, d0 = 0x10325476;
  const M = new Uint32Array(16);
  for (let blk = 0; blk < total; blk++) {
    for (let i = 0; i < 16; i++) M[i] = dv.getUint32(blk * 64 + i * 4, true);
    let A = a0, B = b0, C = c0, D = d0;
    for (let i = 0; i < 64; i++) {
      let F, g;
      if (i < 16) { F = (B & C) | (~B & D); g = i; }
      else if (i < 32) { F = (D & B) | (~D & C); g = (5 * i + 1) % 16; }
      else if (i < 48) { F = B ^ C ^ D; g = (3 * i + 5) % 16; }
      else { F = C ^ (B | ~D); g = (7 * i) % 16; }
      F = (F + A + K[i] + M[g]) >>> 0;
      A = D; D = C; C = B;
      const s = S[(i >> 4) * 4 + (i & 3)];
      B = (B + ((F << s) | (F >>> (32 - s)))) >>> 0;
    }
    a0 = (a0 + A) >>> 0; b0 = (b0 + B) >>> 0; c0 = (c0 + C) >>> 0; d0 = (d0 + D) >>> 0;
  }
  const out = new Uint8Array(16), ov = new DataView(out.buffer);
  [a0, b0, c0, d0].forEach((v, i) => ov.setUint32(i * 4, v, true));
  return out;
}

// ------------------------------------------------------------------ zip (DFU package: manifest.json, firmware.bin, firmware.dat)

export async function readZip(bytes) {
  const dv = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  let eocd = -1;
  for (let i = bytes.length - 22; i >= Math.max(0, bytes.length - 65557); i--) {
    if (dv.getUint32(i, true) === 0x06054b50) { eocd = i; break; }
  }
  if (eocd < 0) throw new Error("not a zip file");
  const count = dv.getUint16(eocd + 10, true);
  let p = dv.getUint32(eocd + 16, true);
  const files = {};
  for (let k = 0; k < count; k++) {
    if (dv.getUint32(p, true) !== 0x02014b50) throw new Error("bad zip directory");
    const method = dv.getUint16(p + 10, true), csize = dv.getUint32(p + 20, true);
    const nlen = dv.getUint16(p + 28, true), xlen = dv.getUint16(p + 30, true), clen = dv.getUint16(p + 32, true);
    const local = dv.getUint32(p + 42, true);
    const name = dec.decode(bytes.subarray(p + 46, p + 46 + nlen));
    const start = local + 30 + dv.getUint16(local + 26, true) + dv.getUint16(local + 28, true);
    const raw = bytes.subarray(start, start + csize);
    if (method === 0) files[name] = raw.slice();
    else if (method === 8) {
      const stream = new Blob([raw]).stream().pipeThrough(new DecompressionStream("deflate-raw"));
      files[name] = new Uint8Array(await new Response(stream).arrayBuffer());
    } else throw new Error(`unsupported zip compression ${method}`);
    p += 46 + nlen + xlen + clen;
  }
  return files;
}

// "MSPAGER-BOARD:<env>\0" in every pager image (PagerOta.h)
export function boardOf(image) {
  const marker = enc.encode("MSPAGER-BOARD:");
  outer: for (let i = 0; i + marker.length < image.length; i++) {
    for (let j = 0; j < marker.length; j++) if (image[i + j] !== marker[j]) continue outer;
    let end = i + marker.length;
    while (end < image.length && image[end] !== 0 && end - i < 80) end++;
    return dec.decode(image.subarray(i + marker.length, end));
  }
  return null;
}

