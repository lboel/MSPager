def parse(art, w, h, name):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == h, f"{name}: {len(rows)} rows, expected {h}"
    for r in rows:
        assert len(r) == w and set(r) <= {"#", "."}, f"{name}: bad row '{r}'"
    return rows


def to_bytes(rows):
    out = []
    for r in rows:
        for i in range(0, len(r), 8):
            b = 0
            for bit, ch in enumerate(r[i:i + 8]):
                if ch == "#":
                    b |= 0x80 >> bit
            out.append(b)
    return out


def hexlist(bs):
    return ", ".join(f"0x{b:02X}" for b in bs)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", help="write a zoomed PNG preview sheet")
    args = ap.parse_args()

    glyphs = [(n, cps, parse(s, 8, 8, n), parse(l, 16, 16, n)) for n, cps, s, l in EMOJIS]
    names = [g[0] for g in glyphs]
    assert len(set(names)) == len(names), "duplicate name"
    all_cps = [cp for g in glyphs for cp in g[1]]
    assert len(set(all_cps)) == len(all_cps), "codepoint mapped twice"

    lines = [
        "#pragma once",
        "",
        "// GENERATED by bin/gen_emoji_glyphs.py - edit the ASCII art there, not this file.",
        "// Emoji drawn on the OLED (FRD-013, FRD-022). Bitmaps are MSB-first rows (drawXbm).",
        "",
        "#include <stdint.h>",
        "",
        f"#define EMOJI_GLYPH_COUNT  {len(glyphs)}",
        "",
        "static const uint8_t EMOJI_SMALL[EMOJI_GLYPH_COUNT][8] = {   // 8x8",
    ]
    for n, cps, s, l in glyphs:
        lines.append(f"  {{ {hexlist(to_bytes(s))} }},   // {n}")
    lines += ["};", "", "static const uint8_t EMOJI_LARGE[EMOJI_GLYPH_COUNT][32] = {   // 16x16"]
    for n, cps, s, l in glyphs:
        lines.append(f"  {{ {hexlist(to_bytes(l))} }},   // {n}")
    lines += ["};", "", "struct EmojiCodepoint { uint32_t cp; uint8_t glyph; };",
              "", "// sorted by codepoint (binary search)", "static const EmojiCodepoint EMOJI_CODEPOINTS[] = {"]
    pairs = sorted((cp, i) for i, g in enumerate(glyphs) for cp in g[1])
    for cp, i in pairs:
        lines.append(f"  {{ 0x{cp:05X}, {i:2d} }},   // {chr(cp)} {glyphs[i][0]}")
    lines += ["};", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(glyphs)} glyphs, {len(pairs)} codepoints")

    doc = [
        "# MSPager — Emoji on the OLED",
        "",
        "GENERATED by `bin/gen_emoji_glyphs.py` (FRD-022). These emoji show as pictures on the pager, in the",
        "small (8×8) and the large (16×16) size. Several codepoints can share one picture (e.g. every",
        "heart colour). Variation selectors (U+FE0F), skin tones and zero-width joiners are ignored.",
        "**Any other emoji shows as a filled block** on the pager (the MeshCore app shows it normally).",
        "",
        "![glyphs](pager_emoji.png)",
        "",
        "| Picture | Meaning | Emoji (first one = preferred) |",
        "|---|---|---|",
    ]
    for n, cps, s, l in glyphs:
        doc.append(f"| `{n}` | {LABELS.get(n, '')} | " + " ".join(f"{chr(cp)} `U+{cp:04X}`" for cp in cps) + " |")
    doc += ["", "To add or change a picture: edit the ASCII art in `bin/gen_emoji_glyphs.py`, run it, rebuild.", ""]
    with open(DOC, "w", encoding="utf-8") as f:
        f.write("\n".join(doc))
    print(f"wrote {DOC}")

    for path in [PNG] + ([args.preview] if args.preview else []):
        from PIL import Image, ImageDraw
        z, cols = 6, 6
        cell_w, cell_h = (8 + 16 + 6) * z, 16 * z + 6 * z
        rows_n = (len(glyphs) + cols - 1) // cols
        img = Image.new("RGB", (cols * cell_w, rows_n * cell_h), (0, 0, 0))
        d = ImageDraw.Draw(img)
        for idx, (n, cps, s, l) in enumerate(glyphs):
            ox, oy = (idx % cols) * cell_w, (idx // cols) * cell_h
            for y, r in enumerate(s):
                for x, ch in enumerate(r):
                    if ch == "#":
                        d.rectangle([ox + x * z, oy + y * z, ox + x * z + z - 2, oy + y * z + z - 2], fill=(90, 200, 255))
            for y, r in enumerate(l):
                for x, ch in enumerate(r):
                    if ch == "#":
                        px = ox + (8 + 2) * z + x * z
                        d.rectangle([px, oy + y * z, px + z - 2, oy + y * z + z - 2], fill=(255, 255, 255))
            d.text((ox, oy + 16 * z + z), n, fill=(255, 200, 0))
        img.save(path)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
